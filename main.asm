; practice3.asm
; Мова: i386 (32-bit)
; Вхід: число в регістрі AX (0...999999)
; Вихід: це число надруковане на консолі через int 0x80
; Збірка: nasm -f elf32 practice3.asm -o practice3.o
; Лінкування: ld -m elf_i386 practice3.o -o practice3

global _start

section .bss
    buffer resb 8          ; буфер для цифр (максимум 6 + '\n' + запас)

section .text
_start:
    ; =============================================
    ; memory: підготовка буфера
    ; =============================================
    mov edi, buffer
    add edi, 7             ; починаємо заповнювати з кінця
    mov byte [edi], 10     ; додаємо '\n'
    dec edi

    ; =============================================
    ; math + logic: розширення AX до 32-біт
    ; =============================================
    movzx eax, ax          ; число з AX в EAX (0..999999)

    ; =============================================
    ; logic: спеціальний випадок для 0
    ; =============================================
    cmp eax, 0
    jne convert_loop

    mov byte [edi], '0'
    dec edi
    jmp print_result

    ; =============================================
    ; loops + math: перетворення числа в ASCII (ділення на 10)
    ; =============================================
convert_loop:
    mov ecx, 10
    xor edx, edx           ; очищаємо EDX перед діленням
    div ecx                ; EAX = EAX / 10, EDX = остача

    ; math: перетворення цифри в ASCII
    add dl, '0'
    mov [edi], dl
    dec edi

    ; loops: продовжуємо поки число не 0
    test eax, eax
    jnz convert_loop

print_result:
    ; =============================================
    ; I/O: підготовка до sys_write
    ; =============================================
    inc edi                ; EDI тепер вказує на першу цифру (або '0')
    lea ecx, [edi]         ; ECX = адреса рядка

    ; обчислюємо довжину (від початку рядка до кінця буфера)
    mov edx, buffer
    add edx, 8
    sub edx, ecx           ; EDX = довжина (включаючи '\n')

    ; =============================================
    ; I/O: sys_write (int 0x80)
    ; =============================================
    mov eax, 4             ; syscall: sys_write
    mov ebx, 1             ; файловий дескриптор: stdout
    int 0x80

    ; =============================================
    ; I/O: sys_exit
    ; =============================================
    mov eax, 1             ; syscall: sys_exit
    xor ebx, ebx           ; код виходу 0
    int 0x80